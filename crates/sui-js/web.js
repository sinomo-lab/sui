// The browser entry point: loads the WebAssembly build and runs apps on a
// canvas.
import initWasm, * as wasm from "./web/sui_web.js";
import { createApi } from "./runtime.js";

await initWasm({ module_or_path: new URL("./web/sui_web_bg.wasm", import.meta.url) });
wasm.__registerClasses(wasm);

/**
 * The canvas an app draws on: the `canvas` option (an element or its id),
 * else the element with id `sui-main-canvas`, else a new canvas filling the
 * page.
 */
function resolveCanvas(canvas) {
  if (canvas instanceof HTMLCanvasElement) {
    return canvas;
  }
  const id = canvas ?? "sui-main-canvas";
  const element = document.getElementById(id);
  if (element instanceof HTMLCanvasElement) {
    return element;
  }
  if (canvas != null) {
    throw new Error(`no canvas element with id '${id}'`);
  }
  const created = document.createElement("canvas");
  created.id = id;
  created.style.position = "fixed";
  created.style.inset = "0";
  document.body.append(created);
  return created;
}

/**
 * Keep `canvas` the size of its container: the closest ancestor with a
 * `data-sui-resize-container` attribute, else its parent, else the
 * viewport when the parent is the page itself. Returns a function that
 * stops.
 */
function fitCanvas(canvas) {
  const container =
    canvas.closest("[data-sui-resize-container]") ?? canvas.parentElement;
  const sizesPage = container === null || container === document.body ||
    container === document.documentElement;
  let frame = 0;
  let last = "";

  const apply = () => {
    frame = 0;
    const rect = sizesPage ? null : container.getBoundingClientRect();
    const width = Math.max(1, rect?.width || window.innerWidth);
    const height = Math.max(1, rect?.height || window.innerHeight);
    const ratio = window.devicePixelRatio || 1;
    const key = `${width}x${height}@${ratio}`;
    if (key === last) {
      return;
    }
    last = key;
    canvas.style.width = `${width}px`;
    canvas.style.height = `${height}px`;
    canvas.width = Math.max(1, Math.round(width * ratio));
    canvas.height = Math.max(1, Math.round(height * ratio));
    // The platform measures the canvas when the window resizes. (The
    // module exports its own `Event`, so name the DOM one explicitly.)
    window.dispatchEvent(new window.Event("resize"));
  };
  const schedule = () => {
    frame ||= requestAnimationFrame(apply);
  };

  const observer = new ResizeObserver(schedule);
  if (!sizesPage) {
    observer.observe(container);
  }
  window.addEventListener("resize", schedule);
  apply();
  return () => {
    observer.disconnect();
    window.removeEventListener("resize", schedule);
    cancelAnimationFrame(frame);
  };
}

function start(app, options) {
  const canvas = resolveCanvas(options.canvas);
  const stopFitting = fitCanvas(canvas);
  try {
    const running = app.startWeb(canvas);
    return {
      pump: (timeout) => running.pump(timeout),
      uiHandle: running.uiHandle,
      maxTurnWaitMs: running.maxTurnWaitMs,
      dispose: stopFitting,
    };
  } catch (error) {
    stopFitting();
    throw error;
  }
}

const api = createApi(wasm, { start });

