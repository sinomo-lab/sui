// The Node entry point: loads the native addon and runs apps from Node's
// event loop.
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { createApi } from "./runtime.js";

function loadNative() {
  // Development builds and tests can point at a cargo-built library, which
  // has a platform library extension rather than `.node`.
  const override = process.env.SUI_JS_NATIVE;
  if (override) {
    const module = { exports: {} };
    process.dlopen(module, override);
    return module.exports;
  }
  const require = createRequire(import.meta.url);
  const { platform, arch } = process;
  const abi = process.versions.modules;
  const candidates = [
    "sui_js.node",
    "sui-js.node",
    `sui_js.${platform}-${arch}.node`,
    `sui-js.${platform}-${arch}.node`,
    `sui_js.${platform}-${arch}-abi${abi}.node`,
    `sui-js.${platform}-${arch}-abi${abi}.node`,
  ];
  const tried = [];
  for (const candidate of candidates) {
    const path = fileURLToPath(new URL(candidate, import.meta.url));
    try {
      return require(path);
    } catch (error) {
      if (error?.code !== "MODULE_NOT_FOUND") {
        throw error;
      }
      tried.push(path);
    }
  }
  throw new Error(
    [
      "Could not load the SUI native binding.",
      "Build it from crates/sui-js with `napi build --platform --release`",
      "or place the generated .node file next to index.js.",
      `Tried: ${tried.join(", ")}`,
    ].join(" "),
  );
}

const api = createApi(loadNative(), {
  start: (app) => app.startPumped(),
  writeFile,
});

